-- Run only in a dedicated test user's schema. The shared fixture executes this
-- PL/SQL block as one command before each test. In SQL*Plus, follow it with /.
DECLARE
    PROCEDURE drop_table_if_exists(table_name VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE 'DROP TABLE ' || table_name || ' CASCADE CONSTRAINTS PURGE';
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE != -942 THEN
                RAISE;
            END IF;
    END;
BEGIN
    drop_table_if_exists('BOOKS');
    drop_table_if_exists('PUBLISHERS');
    drop_table_if_exists('DAB_ORACLE_BOOKS');
    drop_table_if_exists('DAB_ORACLE_SCALARS');

    EXECUTE IMMEDIATE 'CREATE TABLE PUBLISHERS (
        ID NUMBER(10) PRIMARY KEY,
        NAME VARCHAR2(100) NOT NULL
    )';
    EXECUTE IMMEDIATE 'CREATE TABLE BOOKS (
        ID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
        TITLE VARCHAR2(200) NOT NULL,
        PUBLISHER_ID NUMBER(10) NOT NULL REFERENCES PUBLISHERS(ID)
    )';
    EXECUTE IMMEDIATE 'CREATE TABLE DAB_ORACLE_BOOKS (
        ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        TITLE CLOB DEFAULT ''untitled'',
        DOUBLED_ID GENERATED ALWAYS AS (ID * 2)
    )';

    EXECUTE IMMEDIATE 'CREATE TABLE DAB_ORACLE_SCALARS (
        ID NUMBER(10) PRIMARY KEY,
        DATE_VALUE DATE,
        TIMESTAMP_VALUE TIMESTAMP(6),
        OFFSET_VALUE TIMESTAMP(6) WITH TIME ZONE,
        DOUBLE_VALUE BINARY_DOUBLE,
        CHAR_VALUE CHAR(8),
        FLAG_VALUE NUMBER(1) CHECK (FLAG_VALUE IN (0, 1))
    )';

    EXECUTE IMMEDIATE 'INSERT INTO DAB_ORACLE_SCALARS VALUES (
        1, TO_DATE(''2024-02-29 23:59:58'', ''YYYY-MM-DD HH24:MI:SS''),
        TIMESTAMP ''2024-02-29 23:59:58.123456'',
        TO_TIMESTAMP_TZ(''2024-02-29 23:59:58.654321 +05:45'', ''YYYY-MM-DD HH24:MI:SS.FF6 TZH:TZM''),
        1.25d, ''A"\'', 1
    )';
    EXECUTE IMMEDIATE 'INSERT INTO DAB_ORACLE_SCALARS VALUES (
        2, TO_DATE(''2000-01-01 00:00:01'', ''YYYY-MM-DD HH24:MI:SS''),
        TIMESTAMP ''2000-01-01 00:00:01.000001'',
        TO_TIMESTAMP_TZ(''2000-01-01 00:00:01.000001 -07:00'', ''YYYY-MM-DD HH24:MI:SS.FF6 TZH:TZM''),
        -1.7976931348623157E308d, ''ABCDEFGH'', 0
    )';
    EXECUTE IMMEDIATE 'INSERT INTO DAB_ORACLE_SCALARS (ID) VALUES (3)';

    EXECUTE IMMEDIATE 'INSERT INTO PUBLISHERS (ID, NAME) VALUES (1234, ''Big Company'')';
    EXECUTE IMMEDIATE 'INSERT INTO PUBLISHERS (ID, NAME) VALUES (2345, ''Small Company'')';
    EXECUTE IMMEDIATE 'INSERT INTO BOOKS (ID, TITLE, PUBLISHER_ID) VALUES (1, ''Awesome book'', 1234)';
    EXECUTE IMMEDIATE 'INSERT INTO BOOKS (ID, TITLE, PUBLISHER_ID) VALUES (2, ''Also Awesome book'', 1234)';
    EXECUTE IMMEDIATE 'INSERT INTO BOOKS (ID, TITLE, PUBLISHER_ID) VALUES (3, ''Another book'', 2345)';
    COMMIT;
END;
