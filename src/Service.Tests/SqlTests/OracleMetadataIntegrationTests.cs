    [DataTestMethod]
    [DataRow("LONG")]
    [DataRow("LONG RAW")]
    [DataRow("BFILE")]
    [DataRow("XMLTYPE")]
    [DataRow("INTERVAL DAY TO SECOND")]
    [DataRow("INTERVAL YEAR TO MONTH")]
    public async Task UnsupportedColumnsAreSkippedWhileReadsAndMutationsRemainUsable(string sqlType)
    {
        string tableName = "DAB_META_" + Guid.NewGuid().ToString("N")[..12].ToUpperInvariant();
        using OracleConnection connection = new(ConnectionString);
        await connection.OpenAsync();
        await ExecuteAsync(connection, $"CREATE TABLE {tableName} (ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, TITLE VARCHAR2(100) NOT NULL, PAYLOAD {sqlType})");
        try
        {
            var (metadata, config) = CreateProviderWithConfig(new() { ["Sample"] = CreateEntity(tableName, EntitySourceType.Table, EntityActionOperation.All) });
            await metadata.InitializeAsync();
            SourceDefinition definition = metadata.GetSourceDefinition("Sample");
            CollectionAssert.AreEqual(new[] { "ID", "TITLE" }, definition.Columns.Keys.ToArray());
            CollectionAssert.AreEqual(new[] { "ID" }, definition.PrimaryKey);
            Assert.IsTrue(definition.Columns["ID"].IsAutoGenerated);
            Assert.IsFalse(definition.Columns["ID"].IsReadOnly, "BY DEFAULT identities remain explicitly writable after projection.");
            Assert.IsFalse(definition.Columns["TITLE"].IsNullable);

            OracleTestFixture fixture = new(ConnectionString, tableName);
            SqlInsertStructure insert = new("Sample", metadata, fixture.Authorization.Object, fixture.Filter,
                new Dictionary<string, object?> { ["ID"] = 17m, ["TITLE"] = "projected" }, fixture.Http.HttpContext);
            string insertSql = fixture.Builder.Build(insert);
            Assert.IsFalse(insertSql.Contains("PAYLOAD", StringComparison.Ordinal), insertSql);
            DbResultSet inserted = await fixture.Executor.ExecuteQueryAsync(insertSql, insert.Parameters,
                fixture.Executor.ExtractResultSetFromDbDataReaderAsync, dataSourceName: fixture.SourceName);
            Assert.AreEqual("projected", inserted.Rows.Single().Columns["TITLE"]);
            Assert.IsFalse(inserted.Rows.Single().Columns.ContainsKey("PAYLOAD"));

            FindRequestContext context = new("Sample", metadata.EntityToDatabaseObject["Sample"], true)
            {
                First = 10,
                FieldsToBeReturned = definition.Columns.Keys.ToList()
            };
            SqlQueryStructure query = new(context, metadata, fixture.Authorization.Object, config, fixture.Filter, fixture.Http.HttpContext);
            string readSql = fixture.Builder.Build(query);
            Assert.IsFalse(readSql.Contains("PAYLOAD", StringComparison.Ordinal), readSql);
            using JsonDocument read = await fixture.Executor.ExecuteQueryAsync(readSql, query.Parameters,
                fixture.Executor.GetJsonResultAsync<JsonDocument>, dataSourceName: fixture.SourceName);
            JsonElement row = read.RootElement.EnumerateArray().Single();
            Assert.AreEqual(17, row.GetProperty("ID").GetInt32());
            Assert.AreEqual("projected", row.GetProperty("TITLE").GetString());
            Assert.IsFalse(row.TryGetProperty("PAYLOAD", out _));
        }
        finally
        {
            await ExecuteAsync(connection, $"DROP TABLE {tableName} PURGE");
        }
    }

    [DataTestMethod]
    [DataRow("source.key-fields", "the primary key")]
    [DataRow("mappings", "mappings")]
    [DataRow("fields", "fields")]
    [DataRow("fields.include", "fields.include of role 'anonymous'")]
    [DataRow("database policy", "the database policy of role 'anonymous'")]
    [DataRow("source.fields", "source.fields of relationship 'related'")]
    [DataRow("target.fields", "target.fields of relationship 'related'")]
    [DataRow("linking.source.fields", "linking.source.fields of relationship 'related'")]
    [DataRow("linking.target.fields", "linking.target.fields of relationship 'related'")]
    public async Task ExplicitReferencesToSkippedOracleColumnsFailAtStartup(string reference, string expectedSection)
    {
        string tableName = "DAB_META_" + Guid.NewGuid().ToString("N")[..12].ToUpperInvariant();
        using OracleConnection connection = new(ConnectionString);
        await connection.OpenAsync();
        await ExecuteAsync(connection, $"CREATE TABLE {tableName} (ID NUMBER PRIMARY KEY, TITLE VARCHAR2(100), PAYLOAD LONG)");
        try
        {
            Entity entity = CreateEntity(tableName, EntitySourceType.Table, EntityActionOperation.Read);
            entity = reference switch
            {
                "source.key-fields" => entity with { Source = entity.Source with { KeyFields = new[] { "PAYLOAD" } } },
                "mappings" => entity with { Mappings = new() { ["PAYLOAD"] = "legacy" } },
                "fields" => entity with { Fields = new() { new FieldMetadata { Name = "PAYLOAD", Alias = "legacy" } } },
                "fields.include" => entity with { Permissions = Permissions(new(Exclude: new(), Include: new() { "ID", "PAYLOAD" })) },
                "database policy" => entity with { Permissions = Permissions(policy: new(Database: "@item.PAYLOAD ne null")) },
                "source.fields" => entity with { Relationships = Relationship("PAYLOAD", "ID") },
                "target.fields" => entity with { Relationships = Relationship("ID", "PAYLOAD") },
                "linking.source.fields" => entity with { Relationships = Relationship("ID", "ID", tableName, "PAYLOAD", "ID") },
                "linking.target.fields" => entity with { Relationships = Relationship("ID", "ID", tableName, "ID", "PAYLOAD") },
                _ => throw new ArgumentOutOfRangeException(nameof(reference))
            };
            var (metadata, _) = CreateProviderWithConfig(new()
            {
                ["Sample"] = entity,
                ["Related"] = CreateEntity(tableName, EntitySourceType.Table, EntityActionOperation.Read, "Related")
            });

            DataApiBuilderException error = await Assert.ThrowsExceptionAsync<DataApiBuilderException>(() => metadata.InitializeAsync());

            Assert.AreEqual(HttpStatusCode.ServiceUnavailable, error.StatusCode);
            Assert.AreEqual(DataApiBuilderException.SubStatusCodes.ErrorInInitialization, error.SubStatusCode);
            StringAssert.Contains(error.Message, expectedSection);
            StringAssert.Contains(error.Message, "PAYLOAD");
            StringAssert.Contains(error.Message, "LONG");
        }
        finally
        {
            await ExecuteAsync(connection, $"DROP TABLE {tableName} PURGE");
        }
    }

