    public async Task SharedOracleObjectRetainsSkippedColumnsForEachEntity(bool rejectSecondEntity)
    {
        string tableName = "DAB_META_" + Guid.NewGuid().ToString("N")[..12].ToUpperInvariant();
        using OracleConnection connection = new(ConnectionString);
        await connection.OpenAsync();
        await ExecuteAsync(connection, $"CREATE TABLE {tableName} (ID NUMBER PRIMARY KEY, TITLE VARCHAR2(100), PAYLOAD LONG)");
        try
        {
            Entity first = CreateEntity(tableName, EntitySourceType.Table, EntityActionOperation.Read);
            Entity second = CreateEntity(tableName, EntitySourceType.Table, EntityActionOperation.Read, "Related") with
            {
                Permissions = Permissions(new(Exclude: new() { "PAYLOAD" }, Include: new() { "*" }))
            };
            if (rejectSecondEntity)
            {
                second = second with { Mappings = new() { ["PAYLOAD"] = "legacy" } };
            }

            var (metadata, _) = CreateProviderWithConfig(new() { ["Sample"] = first, ["Related"] = second });
            if (rejectSecondEntity)
            {
                DataApiBuilderException error = await Assert.ThrowsExceptionAsync<DataApiBuilderException>(() => metadata.InitializeAsync());
                StringAssert.Contains(error.Message, "Entity 'Related': mappings references column 'PAYLOAD'");
            }
            else
            {
                await metadata.InitializeAsync();
                foreach (string name in new[] { "Sample", "Related" })
                {
                    CollectionAssert.AreEqual(new[] { "ID", "TITLE" }, metadata.GetSourceDefinition(name).Columns.Keys.ToArray());
                    CollectionAssert.AreEqual(new[] { "ID" }, metadata.GetSourceDefinition(name).PrimaryKey);
                }
            }
        }
        finally
        {
            await ExecuteAsync(connection, $"DROP TABLE {tableName} PURGE");
        }
