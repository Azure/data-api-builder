using System;
using System.Collections.Generic;
using System.Data;
using System.Net;
using Azure.DataApiBuilder.Config.ObjectModel;
using Azure.DataApiBuilder.Core.Models;
using Azure.DataApiBuilder.Core.Resolvers;
using Azure.DataApiBuilder.Service.Exceptions;
using Microsoft.VisualStudio.TestTools.UnitTesting;
using Oracle.ManagedDataAccess.Client;

namespace Azure.DataApiBuilder.Service.Tests.UnitTests;

[TestClass, TestCategory("OracleUnit")]
public class OracleCorrectnessUnitTests
{
    [DataTestMethod]
    [DataRow(true)]
    [DataRow(false)]
    public void CreatePolicyOnlyBlocksUpsertsThatCanInsert(bool updateOnly)
    {
        OracleTestFixture fixture = new();
        fixture.Table.SourceDefinition.Columns["ID"].IsAutoGenerated = updateOnly;
        SqlUpsertQueryStructure query = fixture.Upsert(1, "updated");
        query.DbPolicyPredicatesForOperations[EntityActionOperation.Create] = "1 = 0";
        Assert.AreEqual(updateOnly, query.IsFallbackToUpdate);
        if (updateOnly)
        {
            string sql = fixture.Builder.Build(query);
            StringAssert.Contains(sql, "UPDATE");
            StringAssert.Contains(sql, "-20002");
            Assert.IsFalse(sql.Contains("INSERT INTO", StringComparison.Ordinal));
        }
        else
        {
            DataApiBuilderException error = Assert.ThrowsException<DataApiBuilderException>(() => fixture.Builder.Build(query));
            Assert.AreEqual(HttpStatusCode.BadRequest, error.StatusCode);
        }
    }

    [DataTestMethod]
    [DataRow("CLOB", PredicateOperation.Equal, "=")]
    [DataRow("CLOB", PredicateOperation.NotEqual, "!=")]
    [DataRow("NCLOB", PredicateOperation.Equal, "=")]
    [DataRow("NCLOB", PredicateOperation.NotEqual, "!=")]
    public void ClobComparisonsUseLobAwareSql(string type, PredicateOperation operation, string expectedOperator)
    {
        Column column = new("", "T", "TEXT") { DatabaseTypeName = type };
        string sql = new PredicateBuilder().Render(new(new(column), operation, new("@value")));
        string conversion = type == "NCLOB" ? "TO_NCLOB" : "TO_CLOB";
        StringAssert.Contains(sql, $"DBMS_LOB.COMPARE({conversion}(\"TEXT\"), {conversion}(@value))");
        StringAssert.Contains(sql, $" {expectedOperator} 0)");
        Assert.IsFalse(sql.Contains("SUBSTR", StringComparison.Ordinal));
    }

    [DataTestMethod]
    [DataRow("CLOB", false)]
    [DataRow("CLOB", true)]
    [DataRow("NCLOB", false)]
    [DataRow("NCLOB", true)]
    public void ClobSortingAndGroupingReturnClientErrors(string type, bool grouping)
    {
        OracleTestFixture fixture = new();
        fixture.Table.SourceDefinition.Columns["TITLE"].DatabaseTypeName = type;
        SqlQueryStructure query = fixture.Read();
        if (grouping)
        {
            query.GroupByMetadata.Fields.Add("title", new("", fixture.Table.Name, "TITLE"));
        }
        else
        {
            query.OrderByColumns.Add(new("", fixture.Table.Name, "TITLE"));
        }

        DataApiBuilderException error = Assert.ThrowsException<DataApiBuilderException>(() =>
            grouping ? fixture.Builder.BuildAggregation(query, false) : fixture.Builder.Build(query));
        Assert.AreEqual(HttpStatusCode.BadRequest, error.StatusCode);
        StringAssert.Contains(error.Message, "CLOB");
    }

    [DataTestMethod]
    [DataRow("CLOB", OracleDbType.Clob)]
    [DataRow("NCLOB", OracleDbType.NClob)]
    public void ClobParametersPreserveLongStrings(string type, OracleDbType expected)
    {
        OracleTestFixture fixture = new();
        string value = new('x', 6000);
        using OracleConnection connection = new();
        using OracleCommand command = (OracleCommand)fixture.Executor.PrepareDbCommand(connection, "SELECT :value FROM DUAL",
            new Dictionary<string, DbConnectionParam> { ["value"] = new(value, DbType.String) { DatabaseTypeName = type } }, null, fixture.SourceName);
        Assert.AreEqual(expected, command.Parameters[0].OracleDbType);
        Assert.AreEqual(value, command.Parameters[0].Value);
    }

    [DataTestMethod]
    [DataRow(PredicateOperation.LessThan)]
    [DataRow(PredicateOperation.LessThanOrEqual)]
    [DataRow(PredicateOperation.GreaterThan)]
    [DataRow(PredicateOperation.GreaterThanOrEqual)]
    public void ClobRelationalComparisonsAreRejectedInsteadOfAssumingCompareOrdering(PredicateOperation operation)
    {
        Column column = new("", "T", "TEXT") { DatabaseTypeName = "CLOB" };
        DataApiBuilderException error = Assert.ThrowsException<DataApiBuilderException>(() =>
            new PredicateBuilder().Render(new(new(column), operation, new("@value"))));
        Assert.AreEqual(HttpStatusCode.BadRequest, error.StatusCode);
        StringAssert.Contains(error.Message, "relational comparisons");
    }

    private sealed class PredicateBuilder : OracleQueryBuilder
    {
        public string Render(Predicate predicate) => Build(predicate);
    }
}
