    /// <summary>
    /// Schema discovery over MSSQL objects with columns the data provider has no CLR type for, such as geometry
    /// and hierarchyid. Those columns are skipped and the rest of the object is inferred as the data adapter would.
    /// Entities are declared in memory because several fixtures in DatabaseSchema-MsSql.sql fail by design.
    /// </summary>
    [TestClass, TestCategory(TestCategory.MSSQL)]
    public class SqlMetadataProviderUnsupportedColumnTypeTests : SqlTestBase
    {
        private const string ENTITY_NAME = "TestEntity";
        private const string RELATED_ENTITY_NAME = "Related";

        [ClassInitialize]
        public static async Task SetupAsync(TestContext context)
        {
            DatabaseEngine = TestCategory.MSSQL;
            TestHelper.SetupDatabaseEnvironment(DatabaseEngine);
            SetUpSQLMetadataProvider(TestHelper.GenerateInMemoryRuntimeConfigProvider(SqlTestHelper.SetupRuntimeConfig()));
            await ResetDbStateAsync();
        }

        [TestInitialize]
        public void TestInitialize()
        {
            DatabaseEngine = TestCategory.MSSQL;
            TestHelper.SetupDatabaseEnvironment(DatabaseEngine);
        }

        [TestCleanup]
        public void TestCleanup()
        {
            TestHelper.UnsetAllDABEnvironmentVariables();
        }

        [TestMethod]
        public async Task UnsupportedColumnIsSkipped()
        {
            SourceDefinition definition = await InferSourceDefinitionAsync(CreateEntity("dbo.geometry_type_table", EntitySourceType.Table));

            CollectionAssert.AreEqual(new[] { "id", "name" }, definition.Columns.Keys.ToArray());
            CollectionAssert.AreEqual(new[] { "id" }, definition.PrimaryKey);
            Assert.IsTrue(definition.Columns["id"].IsAutoGenerated, "The identity column should stay auto-generated.");
            Assert.IsFalse(definition.Columns["name"].IsNullable, "Nullability should match the database.");
        }

        [TestMethod]
        public async Task IdentityColumnKeepsItsTypeWhenColumnsAreSkipped()
        {
            SourceDefinition definition = await InferSourceDefinitionAsync(
                CreateEntity("dbo.decimal_identity_geometry_table", EntitySourceType.Table));

            Assert.AreEqual(typeof(decimal), definition.Columns["id"].SystemType);
            Assert.IsTrue(definition.Columns["id"].IsAutoGenerated);
        }

        [TestMethod]
        public async Task HiddenPeriodColumnsAreNotInferred()
        {
            SourceDefinition definition = await InferSourceDefinitionAsync(
                CreateEntity("dbo.temporal_geometry_type_table", EntitySourceType.Table));

            CollectionAssert.AreEqual(new[] { "id", "name" }, definition.Columns.Keys.ToArray());
        }

        [TestMethod]
        public async Task ColumnReadableUnderLegacyTypeSystemIsKept()
        {
            SourceDefinition definition = await InferSourceDefinitionAsync(
                CreateEntity("dbo.geometry_type_table", EntitySourceType.Table),
                connectionStringOptions: "Type System Version=SQL Server 2005;");

            Assert.AreEqual(typeof(byte[]), definition.Columns["geom"].SystemType);
        }

        [DataTestMethod]
        [DataRow("dbo.unique_key_geometry_table", EntitySourceType.Table, "code", DisplayName = "Unique key of a table without a primary key")]
        [DataRow("dbo.geometry_all_view", EntitySourceType.View, "id", DisplayName = "View that selects the underlying primary key")]
        [DataRow("dbo.join_geometry_view", EntitySourceType.View, "id", DisplayName = "View over a join")]
        public async Task KeyIsInferredAsTheDataAdapterWould(string databaseObject, EntitySourceType sourceType, string expectedKey)
        {
            SourceDefinition definition = await InferSourceDefinitionAsync(CreateEntity(databaseObject, sourceType));

            CollectionAssert.AreEqual(new[] { expectedKey }, definition.PrimaryKey);
        }

        [DataTestMethod]
        [DataRow("dbo.hierarchyid_unique_table", EntitySourceType.Table, "id", DisplayName = "Table whose unique key is unsupported")]
        [DataRow("dbo.hierarchyid_composite_view", EntitySourceType.View, "tenant_id", DisplayName = "View whose key is partly unsupported")]
        [DataRow("dbo.unique_without_pk_view", EntitySourceType.View, "code", DisplayName = "View that omits the underlying primary key")]
        public async Task ConfiguredKeyIsUsed(string databaseObject, EntitySourceType sourceType, string keyField)
        {
            SourceDefinition definition = await InferSourceDefinitionAsync(
                CreateEntity(databaseObject, sourceType, keyFields: new[] { keyField }));

            CollectionAssert.AreEqual(new[] { keyField }, definition.PrimaryKey);
        }

        [DataTestMethod]
        [DataRow("dbo.hierarchyid_pk_table", EntitySourceType.Table, DisplayName = "Primary key")]
        [DataRow("dbo.hierarchyid_composite_pk_table", EntitySourceType.Table, DisplayName = "Member of a composite primary key")]
        [DataRow("dbo.hierarchyid_unique_table", EntitySourceType.Table, DisplayName = "Unique key of a table without a primary key")]
        [DataRow("dbo.hierarchyid_composite_view", EntitySourceType.View, DisplayName = "Member of a view's key")]
        public async Task UnsupportedKeyColumnFailsInitialization(string databaseObject, EntitySourceType sourceType)
        {
            DataApiBuilderException exception = await InitializeExpectingFailureAsync(CreateEntity(databaseObject, sourceType));

            StringAssert.Contains(exception.Message, "has no usable primary key: key column(s) node (hierarchyid)");
        }

        [DataTestMethod]
        [DataRow("dbo.unique_without_pk_view", DisplayName = "View that omits the underlying primary key")]
        [DataRow("dbo.self_join_geometry_view", DisplayName = "View over a self-join")]
        public async Task ViewWithoutInferableKeyRequiresKeyFields(string databaseObject)
        {
            DataApiBuilderException exception = await InitializeExpectingFailureAsync(CreateEntity(databaseObject, EntitySourceType.View));

            StringAssert.Contains(exception.Message, "Primary key not configured");
        }

        [TestMethod]
        public async Task ObjectWithOnlyUnsupportedColumnsFailsInitialization()
        {
            DataApiBuilderException exception = await InitializeExpectingFailureAsync(
                CreateEntity("dbo.geometry_only_view", EntitySourceType.View, keyFields: new[] { "geom" }));

            StringAssert.Contains(exception.Message, "every column has a data type that is not supported: geom (geometry)");
        }

        [DataTestMethod]
        [DataRow("source.key-fields", "the primary key")]
        [DataRow("mappings", "mappings")]
        [DataRow("fields", "fields")]
        [DataRow("fields.include", "fields.include of role 'anonymous'")]
        [DataRow("database policy", "the database policy of role 'anonymous'")]
        [DataRow("source.fields", "source.fields of relationship 'related'")]
        [DataRow("source.fields with a matching alias", "source.fields of relationship 'related'")]
        [DataRow("target.fields", "target.fields of relationship 'related'")]
        public async Task ReferenceToUnsupportedColumnFailsInitialization(string reference, string expectedSection)
        {
            Entity entity = CreateEntity("dbo.geometry_type_table", EntitySourceType.Table);
            entity = reference switch
            {
                "source.key-fields" => entity with { Source = entity.Source with { KeyFields = new[] { "geom" } } },
                "mappings" => entity with { Mappings = new() { { "geom", "location" } } },
                "fields" => entity with { Fields = new() { new FieldMetadata { Name = "geom", Alias = "location" } } },
                "fields.include" => entity with { Permissions = CreatePermissions(fields: new(Exclude: new(), Include: new() { "id", "geom" })) },
                "database policy" => entity with { Permissions = CreatePermissions(policy: new(Database: "@item.geom ne null")) },
                "source.fields" => entity with { Relationships = CreateRelationship(sourceField: "geom", targetField: "code") },
                // Relationship fields name backing columns, so an alias with the same name doesn't make the reference valid.
                "source.fields with a matching alias" => entity with
                {
                    Fields = new() { new FieldMetadata { Name = "name", Alias = "geom" } },
                    Relationships = CreateRelationship(sourceField: "geom", targetField: "code")
                },
                "target.fields" => entity with { Relationships = CreateRelationship(sourceField: "name", targetField: "geom") },
                _ => throw new ArgumentOutOfRangeException(nameof(reference))
            };

            DataApiBuilderException exception = await InitializeEntitiesExpectingFailureAsync(new()
            {
                { ENTITY_NAME, entity },
                { RELATED_ENTITY_NAME, CreateEntity("dbo.unique_key_geometry_table", EntitySourceType.Table, name: RELATED_ENTITY_NAME) }
            });

            StringAssert.Contains(
                exception.Message,
                $"Entity '{ENTITY_NAME}': {expectedSection} references column 'geom', whose data type 'geometry' is not supported.");
        }

        [DataTestMethod]
        [DataRow("@item.name ne '@item.geom'", null, DisplayName = "Reference inside a string literal")]
        [DataRow("@item.name ne 'it''s @item.geom'", null, DisplayName = "Reference after an escaped quote inside a string literal")]
        [DataRow("@item.geom ne 'x'", "geom", DisplayName = "Alias of a supported column")]
        public async Task PolicyNotReferencingUnsupportedColumnIsAccepted(string policy, string nameAlias)
        {
            Entity entity = CreateEntity("dbo.geometry_type_table", EntitySourceType.Table) with
            {
                Fields = nameAlias is null ? null : new() { new FieldMetadata { Name = "name", Alias = nameAlias } },
                Permissions = CreatePermissions(policy: new(Database: policy))
            };

            SourceDefinition definition = await InferSourceDefinitionAsync(entity);

            Assert.IsFalse(definition.Columns.ContainsKey("geom"));
        }

        [TestMethod]
        public async Task EntitiesNamingTheSameObjectInDifferentCaseShareItsMetadata()
        {
            Entity lower = CreateEntity("dbo.geometry_type_table", EntitySourceType.Table, name: "Lower");
            Entity upper = CreateEntity("dbo.GEOMETRY_TYPE_TABLE", EntitySourceType.Table, name: "Upper");

            await InitializeMetadataProviderAsync(new() { { "Lower", lower }, { "Upper", upper } });
            Assert.IsTrue(_sqlMetadataProvider.GetSourceDefinition("Upper").Columns["id"].IsAutoGenerated);

            DataApiBuilderException exception = await InitializeEntitiesExpectingFailureAsync(new()
            {
                { "Lower", lower },
                { "Upper", upper with { Mappings = new() { { "geom", "location" } } } }
            });
            StringAssert.Contains(exception.Message, "Entity 'Upper': mappings references column 'geom'");
        }

        private static Entity CreateEntity(
            string databaseObject,
            EntitySourceType sourceType,
            string[] keyFields = null,
            string name = ENTITY_NAME)
        {
            return new(
                Source: new(databaseObject, sourceType, Parameters: null, KeyFields: keyFields),
                GraphQL: new(name, $"{name}s"),
                Fields: null,
                Rest: new(),
                Permissions: CreatePermissions(),
                Mappings: null,
                Relationships: null);
        }

        private static EntityPermission[] CreatePermissions(EntityActionFields fields = null, EntityActionPolicy policy = null)
        {
            return new[] { new EntityPermission("anonymous", new[] { new EntityAction(EntityActionOperation.Read, fields, policy) }) };
        }

        private static Dictionary<string, EntityRelationship> CreateRelationship(string sourceField, string targetField)
        {
            return new()
            {
                {
                    "related",
                    new EntityRelationship(
                        Cardinality: Cardinality.One,
                        TargetEntity: RELATED_ENTITY_NAME,
                        SourceFields: new[] { sourceField },
                        TargetFields: new[] { targetField },
                        LinkingObject: null,
                        LinkingSourceFields: Array.Empty<string>(),
                        LinkingTargetFields: Array.Empty<string>())
                }
            };
        }

        private static async Task<SourceDefinition> InferSourceDefinitionAsync(Entity entity, string connectionStringOptions = null)
        {
            await InitializeMetadataProviderAsync(new() { { ENTITY_NAME, entity } }, connectionStringOptions);
            return _sqlMetadataProvider.GetSourceDefinition(ENTITY_NAME);
        }

        private static Task<DataApiBuilderException> InitializeExpectingFailureAsync(Entity entity)
        {
            return InitializeEntitiesExpectingFailureAsync(new() { { ENTITY_NAME, entity } });
        }

        private static async Task<DataApiBuilderException> InitializeEntitiesExpectingFailureAsync(Dictionary<string, Entity> entities)
        {
            DataApiBuilderException exception = await Assert.ThrowsExceptionAsync<DataApiBuilderException>(
                () => InitializeMetadataProviderAsync(entities));

            Assert.AreEqual(HttpStatusCode.ServiceUnavailable, exception.StatusCode);
            Assert.AreEqual(DataApiBuilderException.SubStatusCodes.ErrorInInitialization, exception.SubStatusCode);
            return exception;
        }

        private static async Task InitializeMetadataProviderAsync(Dictionary<string, Entity> entities, string connectionStringOptions = null)
        {
            RuntimeConfig runtimeConfig = SqlTestHelper.SetupRuntimeConfig();
            string connectionString = runtimeConfig.DataSource.ConnectionString;
            if (connectionStringOptions is not null)
            {
                connectionString = $"{connectionString.TrimEnd().TrimEnd(';')};{connectionStringOptions}";
            }

            runtimeConfig = runtimeConfig with
            {
                DataSource = runtimeConfig.DataSource with { ConnectionString = connectionString },
                Entities = new RuntimeEntities(entities)
            };

            SetUpSQLMetadataProvider(TestHelper.GenerateInMemoryRuntimeConfigProvider(runtimeConfig));
            await _sqlMetadataProvider.InitializeAsync();
        }
    }
}
